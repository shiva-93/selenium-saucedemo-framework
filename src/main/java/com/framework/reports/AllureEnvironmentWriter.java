package com.framework.reports;

import com.framework.config.ConfigReader;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.Properties;

/**
 * Writes Allure {@code environment.properties} and copies {@code categories.json}
 * into {@code target/allure-results}.
 * <p>
 * WHY: Allure picks up env + failure categories from the results directory;
 * call from {@code @BeforeSuite} / suite listener in Step 5 (BaseTest).
 */
public final class AllureEnvironmentWriter {

    private static final Logger LOG = LogManager.getLogger(AllureEnvironmentWriter.class);
    private static final Path RESULTS_DIR = Paths.get("target", "allure-results");

    private AllureEnvironmentWriter() {
    }

    public static void write() {
        try {
            Files.createDirectories(RESULTS_DIR);
            writeEnvironment();
            copyCategories();
        } catch (IOException e) {
            LOG.warn("Failed to write Allure environment/categories: {}", e.getMessage());
        }
    }

    private static void writeEnvironment() throws IOException {
        Properties props = new Properties();
        props.setProperty("Browser", ConfigReader.getBrowser());
        props.setProperty("Base.URL", ConfigReader.getBaseUrl());
        props.setProperty("Headless", String.valueOf(ConfigReader.isHeadless()));
        props.setProperty("OS", System.getProperty("os.name") + " " + System.getProperty("os.version"));
        props.setProperty("Java", System.getProperty("java.version"));
        props.setProperty("User", System.getProperty("user.name"));

        Path envFile = RESULTS_DIR.resolve("environment.properties");
        try (OutputStream out = Files.newOutputStream(envFile)) {
            props.store(out, "Allure environment — generated by AllureEnvironmentWriter");
        }
        LOG.info("Wrote Allure environment to {}", envFile.toAbsolutePath());
    }

    private static void copyCategories() throws IOException {
        try (InputStream in = Thread.currentThread()
                .getContextClassLoader()
                .getResourceAsStream("categories.json")) {
            if (in == null) {
                LOG.warn("categories.json not found on classpath; skip copy");
                return;
            }
            Path target = RESULTS_DIR.resolve("categories.json");
            Files.copy(in, target, StandardCopyOption.REPLACE_EXISTING);
            LOG.info("Copied categories.json to {}", target.toAbsolutePath());
        }
    }
}
